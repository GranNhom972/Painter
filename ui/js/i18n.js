const tables = { fr, en };

function storedLanguage() {
  try {
    return localStorage.getItem('paint.lang');
  } catch {
    return null;
  }
}

let lang = storedLanguage() || ((navigator.language || 'fr').toLowerCase().startsWith('fr') ? 'fr' : 'en');

export function language() {
  return lang;
}

export function setLanguage(l) {
  lang = tables[l] ? l : 'fr';
  try {
    localStorage.setItem('paint.lang', lang);
  } catch {
    /* storage unavailable */
  }
  document.documentElement.lang = lang;
  applyTranslations();
}

export function t(key, vars = {}) {
  const s = tables[lang][key] ?? tables.fr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

/** Engine layer names are "Layer N"; show them in the UI language. */
export function layerName(name) {
  const m = /^Layer (\d+)( \(copy\))*$/.exec(name);
  if (!m) return name;
  const copies = (name.match(/ \(copy\)/g) || []).length;
  return t('layers.name', { n: m[1] }) + (' ' + t('layers.copy')).repeat(copies);
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nLabel));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const label = t(el.dataset.i18nTitle);
    el.title = el.dataset.shortcut ? `${label} (${el.dataset.shortcut})` : label;
    el.setAttribute('aria-label', label);
  });
}

export function formatBytes(n) {
  const unit = lang === 'fr' ? ['octets', 'Ko', 'Mo', 'Go'] : ['bytes', 'KB', 'MB', 'GB'];
  let i = 0;
  let v = n;
  while (v >= 1024 && i < unit.length - 1) {
    v /= 1024;
    i++;
  }
  const num = i === 0 ? String(v) : v.toFixed(1);
  return `${lang === 'fr' ? num.replace('.', ',') : num} ${unit[i]}`;
}
